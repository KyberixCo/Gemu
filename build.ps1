param([switch]$Dev)
$ErrorActionPreference = 'Stop'

# Process environment (including CI secrets) overrides the root .env file.
. (Join-Path $PSScriptRoot 'scripts/build-env.ps1')
$buildConfiguration = Get-ScreenScraperBuildConfiguration -EnvPath (Join-Path $PSScriptRoot '.env')
$developerId = $buildConfiguration['GEMU_SCREENSCRAPER_DEVID']
$developerPassword = $buildConfiguration['GEMU_SCREENSCRAPER_DEVPASSWORD']
$softwareName = $buildConfiguration['GEMU_SCREENSCRAPER_SOFTNAME']
if (-not (Get-Command wails -ErrorAction SilentlyContinue)) {
    throw 'No se encuentra wails en PATH.'
}

# Avoid -ldflags: Go records linker arguments in executable build information.
# JSON string escaping also produces valid Go interpreted string literals.
$configurationPath = Join-Path $PSScriptRoot 'internal/providers/content/screenscraper_build_local.go'
$idLiteral = ConvertTo-Json -InputObject ([string]$developerId) -Compress
$passwordLiteral = ConvertTo-Json -InputObject ([string]$developerPassword) -Compress
$nameLiteral = ConvertTo-Json -InputObject ([string]$softwareName) -Compress
$configuration = @"
// Code generated by build.ps1. DO NOT COMMIT.
package content
func init() {
    screenScraperDeveloperID = $idLiteral
    screenScraperDeveloperPassword = $passwordLiteral
    screenScraperSoftwareName = $nameLiteral
}
"@
# A named mutex is scoped to this checkout. Windows releases it even when a
# session is terminated, so an interrupted build cannot leave a permanent lock.
$workspaceName = [IO.Path]::GetFullPath($PSScriptRoot).TrimEnd('\').ToUpperInvariant()
$hasher = [Security.Cryptography.SHA256]::Create()
try { $workspaceHash = [BitConverter]::ToString($hasher.ComputeHash([Text.Encoding]::UTF8.GetBytes($workspaceName))).Replace('-', '') }
finally { $hasher.Dispose() }
$buildMutex = [Threading.Mutex]::new($false, ('Local\GemuBuild-' + $workspaceHash))
$ownsLock = $false
$ownsConfiguration = $false
$pushedLocation = $false
try {
    try { $ownsLock = $buildMutex.WaitOne(0) }
    catch [Threading.AbandonedMutexException] { $ownsLock = $true }
    if (-not $ownsLock) { throw 'Ya hay una sesión de build/dev activa en este repositorio. Cierra esa sesión antes de iniciar otra.' }
    if (Test-Path -LiteralPath $configurationPath) {
        $reader = [IO.File]::OpenText($configurationPath)
        try { $generatedHeader = $reader.ReadLine() } finally { $reader.Dispose() }
        if ($generatedHeader -ne '// Code generated by build.ps1. DO NOT COMMIT.') {
            throw 'El archivo screenscraper_build_local.go no tiene la marca del generador. Se conserva para evitar sobrescribir cambios propios.'
        }
        Write-Host 'Recuperando configuración temporal de una sesión anterior.'
    }
    Push-Location $PSScriptRoot
    $pushedLocation = $true
    $ownsConfiguration = $true
    [IO.File]::WriteAllText($configurationPath, $configuration, [Text.UTF8Encoding]::new($false))
    if ($Dev) { & wails dev @args } else { & wails build @args }
    $buildExitCode = $LASTEXITCODE
}
finally {
    try {
        if ($pushedLocation) { Pop-Location }
        if ($ownsConfiguration -and (Test-Path -LiteralPath $configurationPath)) {
            Remove-Item -LiteralPath $configurationPath -Force
        }
    }
    finally {
        if ($ownsLock) { $buildMutex.ReleaseMutex() }
        $buildMutex.Dispose()
    }
}
exit $buildExitCode
